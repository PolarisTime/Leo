-- 修正 mk_quote_item_purchase_order.allocated_ton 的列注释, 与新分配口径一致。
--
-- 背景: V182 写入的该列注释是「同一行各条之和必须等于 mk_quote_item.ton」(早期口径)。
-- 现在的口径是:
--   · 同一行各条之和不得超过 mk_quote_item.ton —— 超发拒绝(服务层 422);
--   · 允许少于本行吨位 —— 欠额表示"这条报单还有一部分没落到订单上", 是合法业务态。
--     例: 本行报 200 吨, 可关联的采购订单明细行订货量合计只有 130 吨, 前端按
--     min(剩余, 订货量) 分摊后 Σ=130 < 200, 这种常见情形必须能保存。
-- 只拦超发而不是要求严格相等, 否则上述合法业务情形会必然被拒。
--
-- V182 已合入(且已在环境应用), 按仓库迁移规则不得改写, 因此新增本迁移只更新这一条注释:
-- 不改表结构、不改数据、不加约束。单条分配量"不超过该采购订单明细行订货量"由服务层校验
-- (订货量会随采购订单变化, 不适合做成数据库 CHECK/FK), 因此不在这里落库为约束。

COMMENT ON COLUMN public.mk_quote_item_purchase_order.allocated_ton IS
    '本次在该采购订单明细行开出的吨位; 同一行各条之和不得超过 mk_quote_item.ton(超发拒绝), 允许少于本行吨位(欠额表示尚未落到订单上的部分); 单条还不得超过该采购订单明细行的订货量(服务层校验, 非数据库约束)。';
